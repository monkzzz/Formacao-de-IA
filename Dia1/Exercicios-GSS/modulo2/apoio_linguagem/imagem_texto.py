"""Images, requests and runners for the image-and-text exercise (06) with GLM-4.6V."""

from __future__ import annotations

import base64
import json
import time
from dataclasses import asdict, dataclass
from datetime import date
from itertools import product
from pathlib import Path
from typing import Protocol

from matplotlib.figure import Figure

from . import lm_studio
from .interface_base import generated_image

IMAGE_DIRECTORY = (Path(__file__).resolve().parents[1] / "imagens")
RECORDING_PATH = (Path(__file__).resolve().parents[1] / "respostas_gravadas") / "imagem_texto.json"
DOWNTIME_MINUTES = {"Linha 1": 5, "Linha 2": 20, "Linha 3": 8}
LANGUAGE = " Responde em português europeu, em três frases no máximo."


@dataclass(frozen=True)
class ImageCase:
    """One image and the question that is specific to it."""

    key: str
    label: str
    file_name: str
    specific_question: str
    is_generated: bool = False


ANOMALY_QUESTION = "Há alguma anomalia visível? Diz onde está e separa o que observas do que é hipótese."
IMAGES = (
    ImageCase("peca", "Peça (esquema)", "peca_fissura_esquema.png", ANOMALY_QUESTION),
    ImageCase("grafico", "Gráfico de paragens", "grafico_paragens.png",
              "Que linha teve mais minutos de paragem e quantos minutos foram?"),
)
# Photo generated by the trainer for the CLIP slide; used here once it exists.
PHOTO = ImageCase("foto", "Peça (fotografia)", "peca_fissura_foto.png", ANOMALY_QUESTION, is_generated=True)
REQUESTS = ("Descrever", "Pergunta", "Limites")


def available_images() -> tuple[ImageCase, ...]:
    """The prepared images, plus the trainer's photo when it has been generated."""
    return IMAGES + ((PHOTO,) if generated_image(PHOTO.file_name) else ())


@dataclass(frozen=True)
class VisionAnswer:
    """Model answer and how long it took."""

    text: str
    seconds: float
    source: str


def request_text(image: ImageCase, request: str) -> str:
    """Exact text sent with the image."""
    if request == "Descrever":
        return "Descreve a imagem." + LANGUAGE
    if request == "Pergunta":
        return image.specific_question + LANGUAGE
    if request == "Limites":
        return "Que conclusões não se podem tirar só a partir desta imagem?" + LANGUAGE
    raise ValueError(f"Pedido desconhecido: {request}")


def image_path(image: ImageCase) -> Path:
    """Path of the image file, creating the synthetic chart the first time."""
    if image.is_generated:
        generated = generated_image(image.file_name)
        if generated is None:
            raise FileNotFoundError(f"Imagem ainda não gerada: {image.file_name}")
        return generated
    path = IMAGE_DIRECTORY / image.file_name
    if image.key == "grafico" and not path.exists():
        save_downtime_chart(path)
    return path


def save_downtime_chart(path: Path) -> None:
    """Synthetic bar chart of downtime minutes per line (fictitious data)."""
    figure = Figure(figsize=(6, 4), dpi=150)
    axis = figure.subplots()
    lines, minutes = list(DOWNTIME_MINUTES), list(DOWNTIME_MINUTES.values())
    axis.bar(lines, minutes, color=["#4285b4", "#ec9736", "#4285b4"])
    axis.set_title("Minutos de paragem por linha (dados fictícios)")
    axis.set_ylabel("minutos")
    axis.spines[["top", "right"]].set_visible(False)
    figure.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(path)


class VisionRunner(Protocol):
    """Anything that answers a request about an image."""

    def run(self, image: ImageCase, request: str) -> VisionAnswer: ...


class LiveVisionRunner:
    """Send the image and the request to GLM-4.6V in LM Studio."""

    def run(self, image: ImageCase, request: str) -> VisionAnswer:
        encoded = base64.b64encode(image_path(image).read_bytes()).decode("ascii")
        content = [{"type": "text", "text": request_text(image, request)},
                   {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{encoded}"}}]
        start = time.perf_counter()
        # The model reasons before answering; the token budget must cover reasoning and answer.
        choice = lm_studio.request_chat([{"role": "user", "content": content}], lm_studio.VISION_MODEL,
                                        timeout=300.0, temperature=0.2, max_tokens=2000)
        return VisionAnswer(choice["message"]["content"].strip(), round(time.perf_counter() - start, 1), "ao vivo")


class RecordedVisionRunner:
    """Replay answers recorded from GLM-4.6V."""

    def __init__(self, path: Path = RECORDING_PATH) -> None:
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as error:
            raise lm_studio.LmStudioError(f"Gravação de imagem e texto ilegível: {path}") from error
        self.recorded_on, self.answers = data["data"], data["respostas"]

    def run(self, image: ImageCase, request: str) -> VisionAnswer:
        key = f"{image.key}|{request}"
        if key not in self.answers:
            raise lm_studio.LmStudioError("Sem resposta gravada para esta imagem e pedido.")
        return VisionAnswer(**{**self.answers[key], "source": f"gravado em {self.recorded_on}"})


class FallbackVisionRunner:
    """Live model first; the recording if the server fails."""

    def __init__(self, live: VisionRunner | None, recorded: VisionRunner | None) -> None:
        self.live, self.recorded = live, recorded

    def run(self, image: ImageCase, request: str) -> VisionAnswer:
        if self.live is not None:
            try:
                return self.live.run(image, request)
            except lm_studio.LmStudioError:
                self.live = None
        if self.recorded is None:
            raise lm_studio.LmStudioError("LM Studio indisponível e sem gravação.")
        return self.recorded.run(image, request)


def record_all(runner: VisionRunner, path: Path = RECORDING_PATH) -> int:
    """Record every image and request for offline use."""
    answers = {f"{image.key}|{request}": {k: v for k, v in asdict(runner.run(image, request)).items() if k != "source"}
               for image, request in product(available_images(), REQUESTS)}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"modelo": lm_studio.VISION_MODEL, "data": date.today().isoformat(),
                                "respostas": answers}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return len(answers)
